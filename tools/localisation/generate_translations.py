#!/usr/bin/env python3
"""Generate the portable interface tables from the reviewed UTF-8 catalogue."""
from pathlib import Path
import argparse,json
ROOT=Path(__file__).resolve().parents[2]
def render():
 d=json.loads((ROOT/'localisation/translations.json').read_text());tables=d['tables'];keys=set(tables['es'])
 if any(set(t)!=keys for t in tables.values()):raise ValueError('Language key coverage differs')
 lines=['// Generated by tools/localisation/generate_translations.py.','#pragma once','#include <string>','#include <unordered_map>','namespace UiTranslations {','inline const std::unordered_map<std::string,std::string>& Table(int language) {']
 for i,lang in enumerate(d['languages'][1:],1):
  lines+=['    static const std::unordered_map<std::string,std::string> '+lang+' = {']
  for key,value in sorted(tables[lang].items()):
   if not isinstance(value,str) or not value.strip():raise ValueError('Empty translation: '+lang+':'+key)
   lines+=['        {'+json.dumps(key,ensure_ascii=False)+', '+json.dumps(value,ensure_ascii=False)+'},']
  lines+=['    };']
 lines+=['    switch(language) {']
 for i,lang in enumerate(d['languages'][1:],1):lines+=['    case '+str(i)+': return '+lang+';']
 lines+=['    default: { static const std::unordered_map<std::string,std::string> empty; return empty; }','    }','}','} // namespace UiTranslations','']
 return '\n'.join(lines)
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();out=ROOT/'frontend/ui_translations.h';text=render()
 if a.check:
  if not out.exists() or out.read_text()!=text:p.exit(1,'Regenerate ui_translations.h\n')
 else:out.write_text(text)

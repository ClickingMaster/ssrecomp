#!/usr/bin/env python3
"""Generate the new-profile registry from reviewed address metadata."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]

def render(entries):
    lines=['// Generated by tools/regions/generate_profiles.py; address/fingerprint metadata only.',
           '#pragma once','#include <cstddef>','#include <cstdint>','#include <cstring>',
           '#include "../melonDS/src/sha1/sha1.hpp"','namespace RegionalProfiles {',
           'struct Profile { const char *code, *base, *name, *save, *sha1; unsigned revision; size_t bytes; bool functions; uint32_t mapTable, heapSetup, heapUser, mapCount; };',
           'inline constexpr Profile profiles[] = {']
    for e in entries:
        m=e.get('wide_map') or {}
        strings=', '.join(json.dumps(e[k]) for k in ['code','base','name','save','sha1'])
        lines.append('    {'+strings+f', {e["revision"]}, {e["bytes"]}u, '+('true' if e['kind']=='functions' else 'false')+f', 0x{m.get("table",0):08x}u, 0x{m.get("heap_setup",0):08x}u, 0x{m.get("heap_user",0):x}u, {m.get("count",0)}'+'},')
    lines += ['};','inline const Profile* Find(const char* code) {',
              '    for (const auto& p : profiles) if (std::strcmp(code,p.code)==0) return &p;',
              '    return nullptr;','}',
              'inline const char* Check(const Profile& p, const uint8_t* rom, size_t size) {',
              '    if (!rom || size < 0x200 || std::memcmp(rom+12,p.code,4)!=0) return "The regional profile does not match this game.";',
              '    if (rom[30] != p.revision) return "This ROM revision has not been validated for its regional profile.";',
              '    if (size != p.bytes) return "This ROM size has not been validated for its regional profile.";',
              '    SHA1_CTX ctx; SHA1Init(&ctx); SHA1Update(&ctx,rom,(uint32_t)size);',
              '    unsigned char bytes[20]; SHA1Final(bytes,&ctx); char digest[41] = {};',
              '    const char hex[] = "0123456789abcdef";',
              '    for (int i=0;i<20;++i) { digest[2*i]=hex[bytes[i]>>4]; digest[2*i+1]=hex[bytes[i]&15]; }',
              '    if (std::strcmp(digest,p.sha1)!=0) return "This ROM fingerprint has not been validated for its regional profile.";',
              '    return nullptr;','}',
              'inline const char* Check(const uint8_t* rom, size_t size) {',
              '    if (!rom || size < 16) return nullptr;',
              '    char code[5] = {}; std::memcpy(code,rom+12,4);',
              '    const auto* p=Find(code); return p ? Check(*p,rom,size) : nullptr;',
              '}','} // namespace RegionalProfiles','']
    return '\n'.join(lines)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    entries=json.loads((ROOT/'tools/regions/profiles.json').read_text())['profiles']
    if len({e['code'] for e in entries})!=len(entries):p.exit(1,'Duplicate profile code\n')
    for e in entries:
        if e['kind'] not in ('functions','portable') or not (ROOT/e['source']).is_file():p.exit(1,'Invalid profile source\n')
        if len(e['sha1'])!=40 or any(c not in '0123456789abcdef' for c in e['sha1']):p.exit(1,'Invalid fingerprint\n')
    output=ROOT/'frontend/regional_profiles.h';text=render(entries)
    if a.check:
        if not output.exists() or output.read_text()!=text:p.exit(1,'Generated registry is stale\n')
    else:output.write_text(text)
    print(f'{len(entries)} explicit versioned profiles')

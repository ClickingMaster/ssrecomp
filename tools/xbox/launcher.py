#!/usr/bin/env python3
"""The Xbox launcher: the app built without the game's code, so that it needs no ROM to
build and holds nothing of the game. It runs the game on melonDS's interpreter instead of
recompiled code; the player puts their own ROM in the app's folder on the console.
.github/workflows/xbox-launcher.yml builds it on GitHub, for players without a Windows PC.

Usage (Windows, Visual Studio as in xbox.py): python tools/xbox/launcher.py --build-dir <dir>
The package and its certificate end up in <dir>/package.
"""
import argparse
import json
import os
import re
from pathlib import Path
import subprocess
import sys
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools'))
sys.path.insert(0, str(ROOT / 'tools' / 'xbox'))
sys.path.insert(0, str(ROOT / 'tests'))
import recomp
import xbox
import clang_cl_smoke


LAYOUT = ROOT / 'layouts' / 'soulsilver-us.json'
SAMPLES = 16  # code words compared per section to tell which overlay is in memory


def samples(ranges):
    """Up to SAMPLES addresses of whole code words, spread over the section's code."""
    spans = [(start, end) for start, end, _thumb in ranges if end - start >= 4]
    total = sum(end - start - 3 for start, end in spans)
    picked = []
    for k in range(min(SAMPLES, total)):
        target = k * total // min(SAMPLES, total)
        for start, end in spans:
            if target < end - start - 3:
                picked.append((start + target) & ~1)
                break
            target -= end - start - 3
    return sorted(set(picked))


def write_gen(gen):
    """Generated sources without any of the game: no sections are read, so only melonDS's
    own free BIOS is recompiled. The game's sections are listed from the layout with no
    bytes (names and addresses, for the frontend's scene detection), with a watch table
    that the runtime fills from the player's ROM on the console (see recomp_rt.h)."""
    gen.mkdir(parents=True, exist_ok=True)
    with patch.object(recomp, 'load_sections', return_value=[]), patch.object(
            sys, 'argv', ['recomp.py', 'none', str(ROOT / 'melonDS' / 'src'), str(gen)]):
        recomp.main()
    subprocess.run([sys.executable, str(ROOT / 'tools' / 'apps.py'), '--layout', str(LAYOUT), str(gen)], check=True)

    layout = json.loads(LAYOUT.read_text())
    tables = (gen / 'rc_tables.cpp').read_text()
    m = re.search(r'RcSection rc_sections\[\] = \{\n(.*?)\};\nconst melonDS::u32 rc_num_sections = (\d+);', tables, re.S)
    first = int(m.group(2))
    rows, watch, sample_arrays = [], [], []
    for k, sec in enumerate(layout['sections']):
        index = first + k
        rows.append(f'    {{"{sec["name"]}", 0x{sec["base"]:08X}u, 0x{sec["size"]:X}u, nullptr, nullptr, 0, 0, 0}},\n')
        source = -1 if sec['source'] == 'main' else sec['source'] if isinstance(sec['source'], int) else None
        addrs = samples(sec['ranges'])
        if source is None or not addrs:
            continue
        sample_arrays.append(f'static const melonDS::u32 rc_watch_s{index}[] = {{' +
                             ', '.join(f'0x{a:08X}u' for a in addrs) + '};\n')
        watch.append(f'    {{{index}, {source}, {len(addrs)}, rc_watch_s{index}}},\n')
    tables = (tables[:m.start()] + 'RcSection rc_sections[] = {\n' + m.group(1) + ''.join(rows) + '};\n'
              f'const melonDS::u32 rc_num_sections = {first + len(rows)};' + tables[m.end():])
    (gen / 'rc_tables.cpp').write_text(tables)
    (gen / 'watch_table.cpp').write_text(
        '// Generated by tools/xbox/launcher.py from the layout: addresses only.\n#include "recomp_rt.h"\n\n' +
        ''.join(sample_arrays) + '\nstatic const RcWatchSection rc_watch_table[] = {\n' + ''.join(watch) + '};\n'
        f'static const bool rc_watch_registered = (rc_watch_register(rc_watch_table, {len(watch)}), true);\n')
    cm = (gen / 'sources.cmake').read_text()
    (gen / 'sources.cmake').write_text(cm.replace(')', '    "${CMAKE_CURRENT_LIST_DIR}/watch_table.cpp"\n)', 1))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--build-dir', type=Path, required=True)
    args = ap.parse_args()
    build = args.build_dir.resolve()
    gen = build / 'gen-launcher'
    write_gen(gen)
    vs = xbox.find_visual_studio()
    msix = clang_cl_smoke.uwp(build, gen, vs, '-DSSR_LAUNCHER=ON')
    print('Xbox launcher: ' + msix, flush=True)
    for name in sorted(os.listdir(os.path.dirname(msix))):
        print('  ' + name, flush=True)


if __name__ == '__main__':
    main()
